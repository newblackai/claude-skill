#!/usr/bin/env node
/* THE TWO PUBLIC TEXTS THE BLOCKING CHECK READS (lot L7): the OpenAPI document production serves, and the help of the
   CLI npm serves. Regenerated by hand, read in the diff, committed — the CI's check runs on them, never on the network;
   the scheduled watch reads the live ones.
     node scripts/refresh-fixtures.mjs */
import { writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
const doc = await (await fetch(process.env.OPENAPI_URL ?? "https://thenewblack.ai/api/v1/openapi.json")).json();
delete doc.info?.["x-generated-at"];
writeFileSync(new URL("../tests/fixtures/openapi.json", import.meta.url), JSON.stringify(doc, null, 1) + "\n");
/* The CLI writes its help on stderr (stdout is kept for JSON). */
const run = spawnSync("npx", ["-y", "@thenewblack/cli@latest", "help"], { encoding: "utf8" });
const help = `${run.stdout ?? ""}${run.stderr ?? ""}`;
writeFileSync(new URL("../tests/fixtures/cli-help.txt", import.meta.url), help);
console.log(`openapi.json (${Object.keys(doc.paths).length} paths), cli-help.txt (${help.split("\n").length} lines)`);
